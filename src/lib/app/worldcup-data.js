function match(matchNo, group, homeTeam, awayTeam, kickoffAt) {
  return {
    matchNo,
    stage: 'group',
    group,
    homeTeam,
    awayTeam,
    kickoffAt,
    matchDay: kickoffAt.slice(0, 10),
    status: 'scheduled',
    homeScore: null,
    awayScore: null,
  };
}

function question(date, prompt, options, closesAt) {
  return {
    key: `q-${date}`,
    date,
    prompt,
    options,
    closesAt,
    correctAnswer: null,
    points: 2,
  };
}

